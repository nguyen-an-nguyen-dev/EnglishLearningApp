/**
 * Finalize the arena assets:
 *  1. Re-encode every downloaded photo to a <=960px JPEG so the whole set is
 *     light enough to ship in web/public (the raw CC0 originals were ~30 MB).
 *  2. Rewrite the manifest so every word points at /arena/<word>.jpg.
 *  3. Emit backend/database/migration_battle_word_images.sql with one UPDATE
 *     per word (idempotent, safe to re-run on another DB).
 */
import fs from 'node:fs/promises'
import path from 'node:path'
import { execFileSync } from 'node:child_process'

const ROOT = 'C:/Users/ADMIN/Desktop/DoAn/EnglishLearningApp'
const OUT = path.join(ROOT, 'web/public/arena')
const MANIFEST = path.join(ROOT, '.workbuddy-ai/tmp-shots/arena-manifest.json')
const SQL = path.join(ROOT, 'backend/database/migration_battle_word_images.sql')

const manifest = JSON.parse(await fs.readFile(MANIFEST, 'utf8'))
if (manifest.length !== 100) {
  console.warn(`WARNING: manifest has ${manifest.length} entries, expected 100`)
}

let compressed = 0
let failed = []
const before = { bytes: 0 }
const after = { bytes: 0 }

for (const entry of manifest) {
  const src = path.join(OUT, path.basename(entry.file))
  const tmp = path.join(OUT, `${entry.word}.tmp.jpg`)
  const dest = path.join(OUT, `${entry.word}.jpg`)
  try {
    const stat = await fs.stat(src)
    before.bytes += stat.size
    execFileSync('ffmpeg', [
      '-hide_banner', '-loglevel', 'error', '-y',
      '-i', src,
      '-vf', "scale=w='min(960,iw)':h=-2,format=yuvj420p",
      '-q:v', '4', '-map_metadata', '-1', '-frames:v', '1',
      tmp,
    ], { stdio: 'pipe', timeout: 60000 })
    const tmpStat = await fs.stat(tmp)
    if (tmpStat.size < 3000) throw new Error(`suspiciously small output ${tmpStat.size}`)
    await fs.rename(tmp, dest)
    after.bytes += tmpStat.size
    entry.file = `/arena/${entry.word}.jpg`
    compressed++
  } catch (err) {
    failed.push(`${entry.word}: ${err.message}`)
    try { await fs.rm(tmp, { force: true }) } catch { /* noop */ }
  }
}

// Drop any leftover .png / .tmp files now that every word has a .jpg.
const leftovers = (await fs.readdir(OUT)).filter((f) => !f.endsWith('.jpg'))
for (const f of leftovers) await fs.rm(path.join(OUT, f), { force: true })

manifest.sort((a, b) => a.word.localeCompare(b.word))
await fs.writeFile(MANIFEST, JSON.stringify(manifest, null, 2))

const lines = [
  '-- Arena vocabulary illustrations (CC0 / public domain from Openverse & Wikimedia Commons).',
  '-- Files live in web/public/arena/<word>.jpg; the web app serves them from /arena/...',
  '-- Idempotent: re-running this on any database only refreshes image_url values.',
  '-- Generated by .workbuddy-ai/tmp-shots/arena-finalize.mjs',
  '',
  'START TRANSACTION;',
  '',
  ...manifest.map((e) => `UPDATE battle_words SET image_url = '${e.file}' WHERE word_en = '${e.word}';`),
  '',
  'COMMIT;',
  '',
  "-- Sanity check: SELECT COUNT(*) FROM battle_words WHERE image_url IS NOT NULL; -- expect 100",
  '',
]
await fs.writeFile(SQL, lines.join('\n'))

console.log(`re-encoded ${compressed}/${manifest.length} images`)
console.log(`size ${(before.bytes / 1048576).toFixed(1)} MB -> ${(after.bytes / 1048576).toFixed(1)} MB`)
if (leftovers.length) console.log(`removed ${leftovers.length} leftover files: ${leftovers.join(', ')}`)
if (failed.length) console.log('FAILED:\n' + failed.join('\n'))
console.log(`wrote ${SQL}`)
