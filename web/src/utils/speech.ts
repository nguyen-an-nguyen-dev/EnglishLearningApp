import { synthesizeSpeechApi, type SpeechVoiceLang } from '../services/speechService'

export interface SpeechHandlers {
  signal?: AbortSignal
  onStart?: () => void
  /** Share of the text already spoken, from 0 to 1. */
  onProgress?: (ratio: number) => void
  onEnd?: () => void
  onStop?: () => void
  onPlayback?: (player: HTMLAudioElement | null) => void
}

interface Playback {
  stop: () => void
}

let active: Playback | null = null

/** Stops whatever is playing. Does not call the `onEnd` of the stopped playback. */
export function stopSpeaking(): void {
  const current = active
  active = null
  current?.stop()
}

const MAX_TTS_CHARS = 500
const TTS_LOOKAHEAD_SECONDS = 2
const TTS_LOOKAHEAD_TIMEOUT_MS = 3_000

function splitTtsText(text: string): string[] {
  const parts: string[] = []
  let remaining = text
  while (remaining.length > MAX_TTS_CHARS) {
    const window = remaining.slice(0, MAX_TTS_CHARS + 1)
    const wordBoundary = window.lastIndexOf(' ')
    let end = wordBoundary > 0 ? wordBoundary : MAX_TTS_CHARS
    const last = remaining.charCodeAt(end - 1)
    if (last >= 0xd800 && last <= 0xdbff) end -= 1
    parts.push(remaining.slice(0, end))
    remaining = remaining.slice(end).trimStart()
  }
  if (remaining) parts.push(remaining)
  return parts
}

/**
 * Reads `text` aloud using MP3 generated by the backend's Edge TTS service.
 * Progress and end are reported through `handlers`.
 */
export function speakText(text: string, lang: SpeechVoiceLang, handlers: SpeechHandlers = {}): boolean {
  const clean = text.trim()
  if (!clean || typeof window === 'undefined' || handlers.signal?.aborted) return false
  stopSpeaking()

  let finished = false
  let started = false
  let audio: HTMLAudioElement | null = null
  let objectUrl: string | null = null
  let frame = 0
  let nextClip: { index: number; result: Promise<Blob | null> } | null = null
  const controller = new AbortController()
  const parts = splitTtsText(clean.replace(/\s+/g, ' '))
  const notifyStarted = () => {
    if (started || finished) return
    started = true
    handlers.onStart?.()
  }

  const releaseAudio = () => {
    cancelAnimationFrame(frame)
    const player = audio
    audio = null
    player?.pause()
    if (player) handlers.onPlayback?.(null)
    if (objectUrl) URL.revokeObjectURL(objectUrl)
    objectUrl = null
  }

  const finish = () => {
    if (finished) return
    finished = true
    nextClip = null
    controller.abort()
    releaseAudio()
    if (active === playback) active = null
    handlers.signal?.removeEventListener('abort', stopOnAbort)
    handlers.onEnd?.()
  }

  const stopOnAbort = () => {
    if (active === playback) stopSpeaking()
  }

  const playback: Playback = {
    stop: () => {
      finished = true
      nextClip = null
      controller.abort()
      releaseAudio()
      handlers.signal?.removeEventListener('abort', stopOnAbort)
      handlers.onStop?.()
    },
  }

  const run = async (index: number) => {
    let blob: Blob
    try {
      const prefetched = nextClip?.index === index ? nextClip.result : null
      nextClip = null
      const ready = prefetched ? await prefetched : null
      if (finished) return
      blob = ready ?? await synthesizeSpeechApi(parts[index], lang, controller.signal, { retryUnavailable: true })
    } catch {
      finish()
      return
    }
    if (finished) return
    objectUrl = URL.createObjectURL(blob)
    const player = new Audio(objectUrl)
    audio = player
    const prefetchNext = () => {
      if (finished || audio !== player || player.paused || nextClip || index + 1 >= parts.length) return
      const secondsLeft = player.duration - player.currentTime
      if (!(secondsLeft >= 0 && secondsLeft <= TTS_LOOKAHEAD_SECONDS)) return
      const signal = AbortSignal.any([controller.signal, AbortSignal.timeout(TTS_LOOKAHEAD_TIMEOUT_MS)])
      nextClip = { index: index + 1, result: synthesizeSpeechApi(parts[index + 1], lang, signal).catch(() => null) }
    }
    player.onplaying = () => {
      if (finished || audio !== player) return
      handlers.onPlayback?.(player)
      notifyStarted()
      prefetchNext()
    }
    player.ontimeupdate = prefetchNext
    player.onwaiting = player.onpause = () => {
      if (!finished && audio === player) handlers.onPlayback?.(null)
    }
    player.onended = () => {
      if (finished || audio !== player) return
      if (index + 1 === parts.length) {
        finish()
      } else {
        releaseAudio()
        void run(index + 1)
      }
    }
    player.onerror = () => {
      if (audio === player) finish()
    }
    const tick = () => {
      if (finished || audio !== player) return
      if (Number.isFinite(player.duration) && player.duration > 0) {
        const progress = Math.min(1, player.currentTime / player.duration)
        handlers.onProgress?.((index + progress) / parts.length)
      }
      frame = requestAnimationFrame(tick)
    }
    try {
      await player.play()
    } catch {
      if (audio === player) finish()
      return
    }
    if (handlers.onProgress && !finished && audio === player) frame = requestAnimationFrame(tick)
  }

  active = playback
  handlers.signal?.addEventListener('abort', stopOnAbort, { once: true })
  void run(0)
  return true
}

/** Pronounces a single English word, e.g. from a vocabulary card. */
export function speakEnglish(value: string): void {
  speakText(value.replace(/[^a-zA-Z' ]/g, ''), 'en')
}
